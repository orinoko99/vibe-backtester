class TestИнструментыРисования:
    """Тесты инструментов рисования."""

    def test_создание_менеджера(self, qtbot):
        """Создание менеджера рисования."""
        график = График()
        qtbot.add_widget(график)

        рисование = ИнструментыРисования(график)
        assert рисование.получить_все() == []

    def test_добавить_горизонтальную_линию(self, qtbot):
        """Добавление горизонтальной линии."""
        график = График()
        qtbot.add_widget(график)

        рисование = ИнструментыРисования(график)
        линия = рисование.добавить_горизонтальную_линию(100.0, имя="Тест")
        assert isinstance(линия, ГоризонтальнаяЛиния)
        assert линия.цена == 100.0
        assert линия in рисование.получить_все()

    def test_добавить_вертикальную_линию(self, qtbot):
        """Добавление вертикальной линии."""
        график = График()
        qtbot.add_widget(график)

        рисование = ИнструментыРисования(график)
        линия = рисование.добавить_вертикальную_линию(1000.0, имя="Время")
        assert isinstance(линия, ВертикальнаяЛиния)

    def test_добавить_текстовую_метку(self, qtbot):
        """Добавление текстовой метки."""
        график = График()
        qtbot.add_widget(график)

        рисование = ИнструментыРисования(график)
        метка = ТекстоваяМетка("Привет", 100.0, 200.0)
        график.addItem(метка)
        assert isinstance(метка, ТекстоваяМетка)

    def test_добавить_прямоугольник(self, qtbot):
        """Добавление прямоугольника."""
        график = График()
        qtbot.add_widget(график)

        рисование = ИнструментыРисования(график)
        прямоугольник = рисование.добавить_прямоугольник(
            100.0, 200.0, 200.0, 100.0
        )
        assert isinstance(прямоугольник, Прямоугольник)

    def test_добавить_трендовую_линию(self, qtbot):
        """Добавление трендовой линии."""
        график = График()
        qtbot.add_widget(график)

        рисование = ИнструментыРисования(график)
        линия = рисование.добавить_трендовую_линию(
            100.0, 100.0, 200.0, 150.0
        )
        assert isinstance(линия, ТрендоваяЛиния)

    def test_удалить_все_рисунки(self, qtbot):
        """Удаление всех рисунков."""
        график = График()
        qtbot.add_widget(график)

        рисование = ИнструментыРисования(график)
        рисование.добавить_горизонтальную_линию(100.0)
        рисование.добавить_вертикальную_линию(200.0)
        assert len(рисование.получить_все()) == 2

        рисование.удалить_все()
        assert рисование.получить_все() == []


