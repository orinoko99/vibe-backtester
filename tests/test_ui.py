class TestСвечаГрафик:
    """Тесты класса СвечаГрафик."""

    def test_создание_без_данных(self):
        """Создание объекта без данных."""
        свечи = СвечаГрафик()
        assert свечи.данные is None

    def test_создание_с_данными(self, тестовые_данные_свечей):
        """Создание объекта с данными."""
        свечи = СвечаГрафик(тестовые_данные_свечей)
        assert свечи.данные is not None
        assert свечи.данные.shape == тестовые_данные_свечей.shape

    def test_обновить_данные(self, тестовые_данные_свечей):
        """Метод обновить должен менять данные."""
        свечи = СвечаГрафик()
        свечи.обновить(тестовые_данные_свечей)
        assert свечи.данные is not None
        assert len(свечи.данные) == 50

    def test_ограничивающий_прямоугольник(self, тестовые_данные_свечей):
        """boundingRect не должен быть пустым при наличии данных."""
        свечи = СвечаГрафик(тестовые_данные_свечей)
        rect = свечи.boundingRect()
        assert rect.width() > 0
        assert rect.height() > 0

    def test_переключение_объёма(self, тестовые_данные_свечей):
        """Переключение отображения объёма не должно вызывать ошибок."""
        свечи = СвечаГрафик(тестовые_данные_свечей)
        свечи.установить_показ_объёма(False)
        свечи.установить_показ_объёма(True)


