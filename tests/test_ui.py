class TestГрафик:
    """Тесты класса График."""

    def test_создание_графика(self, qtbot):
        """Создание виджета графика."""
        график = График()
        qtbot.add_widget(график)
        assert график.список_инструментов == []

    def test_добавить_инструмент(self, qtbot, тестовый_dataframe):
        """Добавление инструмента на график."""
        график = График()
        qtbot.add_widget(график)

        результат = график.добавить_инструмент("TEST", тестовый_dataframe)
        assert результат is True
        assert "TEST" in график.список_инструментов

    def test_добавить_дубликат(self, qtbot, тестовый_dataframe):
        """Повторное добавление того же инструмента должно вернуть False."""
        график = График()
        qtbot.add_widget(график)

        график.добавить_инструмент("TEST", тестовый_dataframe)
        результат = график.добавить_инструмент("TEST", тестовый_dataframe)
        assert результат is False

    def test_удалить_инструмент(self, qtbot, тестовый_dataframe):
        """Удаление инструмента с графика."""
        график = График()
        qtbot.add_widget(график)

        график.добавить_инструмент("TEST", тестовый_dataframe)
        результат = график.удалить_инструмент("TEST")
        assert результат is True
        assert график.список_инструментов == []

    def test_удалить_несуществующий(self, qtbot):
        """Удаление несуществующего инструмента."""
        график = График()
        qtbot.add_widget(график)

        результат = график.удалить_инструмент("NONEXISTENT")
        assert результат is False

    def test_очистить_график(self, qtbot, тестовый_dataframe):
        """Очистка всех инструментов."""
        график = График()
        qtbot.add_widget(график)

        график.добавить_инструмент("A", тестовый_dataframe)
        график.добавить_инструмент("B", тестовый_dataframe)
        график.очистить()
        assert график.список_инструментов == []

    def test_показать_объём(self, qtbot, тестовый_dataframe):
        """Переключение объёма на графике."""
        график = График()
        qtbot.add_widget(график)

        график.добавить_инструмент("TEST", тестовый_dataframe)
        график.показать_объём(False)
        график.показать_объём(True)


