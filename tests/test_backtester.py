        # close первой свечи = 101, проскальзывание 1% -> цена входа = 101 * 1.01 = 102.01
        ожидаемая_цена = 101.0 * 1.01
        assert сделка.цена_входа == pytest.approx(ожидаемая_цена, rel=1e-3)


