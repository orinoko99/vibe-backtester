class СтратегияПростая(Стратегия):
    """
    Тестовая стратегия: покупает на первой свече,
    продаёт на второй, закрывает на третьей.
    """
    def __init__(self) -> None:
        super().__init__()
        self._шаг = 0

    def init(self) -> None:
        self._шаг = 0

    def next(self) -> None:
        if self._шаг == 0:
            self.купить(размер=10, комментарий="вход")
        elif self._шаг == 1:
            self.продать(размер=5, комментарий="частичная")
        elif self._шаг == 2:
            self.закрыть(комментарий="выход")
        self._шаг += 1


class СтратегияБезСигналов(Стратегия):
    """Тестовая стратегия без генерации сигналов."""
    def init(self) -> None:
        pass

    def next(self) -> None:
        pass


class СтратегияТрендовая(Стратегия):
    """
    Тестовая стратегия: покупает если close выше SMA(3),
    продаёт если ниже.
    """
    def __init__(self) -> None:
        super().__init__()
        self.sma: Optional[pd.Series] = None

    def init(self) -> None:
        if self.данные is not None:
            self.sma = self.данные["close"].rolling(3).mean()

    def next(self) -> None:
        if self.данные is None or self.sma is None:
            return
        цена = float(self.данные.iloc[self._индекс]["close"])
        sma_значение = float(self.sma.iloc[self._индекс])

        if pd.isna(sma_значение):
            return

        if цена > sma_значение and self.позиция <= 0:
            self.купить(размер=1, комментарий="тренд вверх")
        elif цена < sma_значение and self.позиция >= 0:
            self.продать(размер=1, комментарий="тренд вниз")


