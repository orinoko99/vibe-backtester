class TestПолучитьСписокТаблиц:
    """Тесты функции получить_список_таблиц."""

    def test_список_таблиц_содержит_тестовую(self, временная_бд):
        """Должен вернуть список, содержащий 'TEST_M1'."""
        таблицы = получить_список_таблиц(временная_бд)
        assert "TEST_M1" in таблицы

    def test_список_таблиц_пустой_бд(self):
        """Должен вернуть пустой список для пустой БД."""
        with tempfile.NamedTemporaryFile(suffix=".db", delete=False) as tmp:
            путь = Path(tmp.name)
        # Создаём пустую БД
        соединение = sqlite3.connect(str(путь))
        соединение.close()

        try:
            таблицы = получить_список_таблиц(путь)
            assert таблицы == []
        finally:
            путь.unlink(missing_ok=True)

    def test_список_таблиц_не_содержит_sqlite_sequence(self, временная_бд):
        """
        Должен НЕ включать служебные таблицы sqlite_sequence и т.п.
        (sqlite_master уже отфильтрован по type='table').
        """
        таблицы = получить_список_таблиц(временная_бд)
        assert "sqlite_sequence" not in таблицы


