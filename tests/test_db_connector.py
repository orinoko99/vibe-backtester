class TestПолучитьСвечи:
    """Тесты функции получить_свечи."""

    def test_загружает_все_записи(self, временная_бд):
        """Должен загрузить все записи из таблицы."""
        свечи = получить_свечи(временная_бд, "TEST_M1")
        assert len(свечи) == 4

    def test_лимит_ограничивает_записи(self, временная_бд):
        """Должен загрузить только указанное количество записей."""
        свечи = получить_свечи(временная_бд, "TEST_M1", лимит=2)
        assert len(свечи) == 2

    def test_смещение_пропускает_записи(self, временная_бд):
        """Должен пропустить указанное количество записей."""
        свечи = получить_свечи(временная_бд, "TEST_M1", лимит=1, смещение=2)
        assert len(свечи) == 1
        assert свечи[0]["ID"] == 3

    def test_структура_записи(self, временная_бд):
        """Должен содержать все необходимые колонки."""
        свечи = получить_свечи(временная_бд, "TEST_M1", лимит=1)
        запись = свечи[0]
        assert set(запись.keys()) >= {
            "ID", "Date", "SecCode", "ClassCode",
            "O", "H", "L", "C", "V", "OpenInterest",
        }

    def test_данные_корректны(self, временная_бд):
        """Проверка корректности загруженных данных."""
        свечи = получить_свечи(временная_бд, "TEST_M1", лимит=1)
        запись = свечи[0]
        assert запись["SecCode"] == "TEST"
        assert запись["O"] == "65.91"
        assert запись["H"] == "66.22"
        assert запись["L"] == "65.91"
        assert запись["C"] == "66.22"
        assert запись["V"] == 2

    def test_запрос_несуществующей_таблицы(self, временная_бд):
        """Должен выбросить исключение для несуществующей таблицы."""
        with pytest.raises(Exception):
            получить_свечи(временная_бд, "NONEXISTENT_TABLE")


