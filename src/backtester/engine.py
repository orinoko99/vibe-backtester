"""
Ядро бэктестера — выполняет прогон стратегии на исторических данных
и рассчитывает метрики производительности.
"""

from dataclasses import dataclass, field
from typing import Optional

import numpy as np
import pandas as pd

from src.backtester.strategy import Стратегия


@dataclass
class Сделка:
    """
    Информация о совершённой сделке.

    Атрибуты
    ---------
    дата_входа : pd.Timestamp
        Дата и время открытия позиции.
    дата_выхода : pd.Timestamp
        Дата и время закрытия позиции.
    тип : str
        Тип сделки: 'long' или 'short'.
    цена_входа : float
        Цена открытия позиции.
    цена_выхода : float
        Цена закрытия позиции.
    размер : float
        Размер позиции.
    pnl : float
        Прибыль/убыток сделки.
    pnl_процент : float
        Прибыль/убыток в процентах.
    """
    дата_входа: pd.Timestamp
    дата_выхода: pd.Timestamp
    тип: str
    цена_входа: float
    цена_выхода: float
    размер: float
    pnl: float = 0.0
    pnl_процент: float = 0.0


@dataclass
class РезультатБэктеста:
    """
    Результаты прогона бэктестера.

    Атрибуты
    ---------
    сделки : list[Сделка]
        Список совершённых сделок.
    эквити : pd.Series
        Кривая капитала (equity curve).
    история_позиций : pd.Series
        История изменения позиции (размера).
    метрики : dict
        Словарь с метриками производительности.
    """
    сделки: list[Сделка] = field(default_factory=list)
    эквити: pd.Series = field(default_factory=pd.Series)
    история_позиций: pd.Series = field(default_factory=pd.Series)
    метрики: dict = field(default_factory=dict)


class Бэктестер:
    """
    Основной класс бэктестера.

    Принимает стратегию и данные, выполняет прогон,
    рассчитывает метрики производительности.

    Параметры
    ----------
    начальный_капитал : float
        Начальный капитал для тестирования (по умолчанию 100000).
    комиссия : float
        Комиссия на сделку в процентах (по умолчанию 0.01%).
    проскальзывание : float
        Проскальзывание в процентах (по умолчанию 0.01%).
    """

    def __init__(
        self,
        начальный_капитал: float = 100_000.0,
        комиссия: float = 0.0001,
        проскальзывание: float = 0.0001,
    ) -> None:
        self.начальный_капитал = начальный_капитал
        self.комиссия = комиссия
        self.проскальзывание = проскальзывание

    def прогнать(
        self,
        стратегия: Стратегия,
        данные: pd.DataFrame,
    ) -> РезультатБэктеста:
        """
        Запускает бэктест стратегии на исторических данных.

        Параметры
        ----------
        стратегия : Стратегия
            Экземпляр класса стратегии.
        данные : pd.DataFrame
            DataFrame с колонками open, high, low, close, volume.

        Возвращает
        -------
        РезультатБэктеста
            Объект с результатами (сделки, кривая капитала, метрики).
        """
        # Устанавливаем данные стратегии и запускаем
        стратегия.установить_данные(данные)
        стратегия.запустить()

        # Обрабатываем сигналы
        капитал = self.начальный_капитал
        позиция = 0.0
        цена_входа = 0.0
        тип_входа: Optional[str] = None
        дата_входа: Optional[pd.Timestamp] = None

        сделки: list[Сделка] = []
        эквити: list[float] = []
        история_позиций: list[float] = []

        for сигнал in стратегия.сигналы:
            дата = сигнал["datetime"]
            цена = сигнал["цена"]
            тип = сигнал["тип"]
            размер = сигнал["размер"]
            комментарий = сигнал["комментарий"]

            if тип == "buy":
                # Закрываем short если был
                if позиция < 0:
                    сделка = Сделка(
                        дата_входа=дата_входа or дата,
                        дата_выхода=дата,
                        тип="short",
                        цена_входа=цена_входа,
                        цена_выхода=цена,
                        размер=abs(позиция),
                    )
                    pnl = (цена_входа - цена) * abs(позиция)
                    pnl -= сделка.цена_выхода * сделка.размер * self.комиссия
                    pnl -= сделка.цена_входа * abs(позиция) * self.комиссия
                    сделка.pnl = pnl
                    сделка.pnl_процент = (pnl / капитал) * 100
                    сделки.append(сделка)
                    капитал += pnl

                # Открываем long
                позиция += размер
                if позиция > 0:
                    цена_входа = цена * (1 + self.проскальзывание)
                    дата_входа = дата
                    тип_входа = "long"

            elif тип == "sell":
                # Закрываем long если был
                if позиция > 0:
                    сделка = Сделка(
                        дата_входа=дата_входа or дата,
                        дата_выхода=дата,
                        тип="long",
                        цена_входа=цена_входа,
                        цена_выхода=цена,
                        размер=позиция,
                    )
                    pnl = (цена - цена_входа) * позиция
                    pnl -= сделка.цена_выхода * сделка.размер * self.комиссия
                    pnl -= сделка.цена_входа * позиция * self.комиссия
                    сделка.pnl = pnl
                    сделка.pnl_процент = (pnl / капитал) * 100
                    сделки.append(сделка)
                    капитал += pnl

                # Открываем short
                позиция -= размер
                if позиция < 0:
                    цена_входа = цена * (1 - self.проскальзывание)
                    дата_входа = дата
                    тип_входа = "short"

            elif тип == "close":
                if позиция > 0:
                    сделка = Сделка(
                        дата_входа=дата_входа or дата,
                        дата_выхода=дата,
                        тип="long",
                        цена_входа=цена_входа,
                        цена_выхода=цена,
                        размер=позиция,
                    )
                    pnl = (цена - цена_входа) * позиция
                    pnl -= сделка.цена_выхода * сделка.размер * self.комиссия
                    pnl -= сделка.цена_входа * позиция * self.комиссия
                    сделка.pnl = pnl
                    сделка.pnl_процент = (pnl / капитал) * 100
                    сделки.append(сделка)
                    капитал += pnl
                elif позиция < 0:
                    сделка = Сделка(
                        дата_входа=дата_входа or дата,
                        дата_выхода=дата,
                        тип="short",
                        цена_входа=цена_входа,
                        цена_выхода=цена,
                        размер=abs(позиция),
                    )
                    pnl = (цена_входа - цена) * abs(позиция)
                    pnl -= сделка.цена_выхода * сделка.размер * self.комиссия
                    pnl -= сделка.цена_входа * abs(позиция) * self.комиссия
                    сделка.pnl = pnl
                    сделка.pnl_процент = (pnl / капитал) * 100
                    сделки.append(сделка)
                    капитал += pnl
                позиция = 0.0
                цена_входа = 0.0
                тип_входа = None
                дата_входа = None

            # Записываем состояние
            эквити.append(капитал + позиция * цена)
            история_позиций.append(позиция)

        # Строим кривую капитала по всем данным
        эквити_серия = pd.Series(
            data=self.начальный_капитал,
            index=данные.index,
            dtype=float,
        )
        текущий_капитал = self.начальный_капитал
        текущая_позиция = 0.0
        for idx in эквити_серия.index:
            if idx in [с.дата_выхода for с in сделки]:
                for с in сделки:
                    if с.дата_выхода == idx:
                        текущий_капитал += с.pnl
                        текущая_позиция = 0.0
            эквити_серия[idx] = текущий_капитал + (
                текущая_позиция * данные.loc[idx, "close"] if текущая_позиция != 0 else 0
            )

        # Если есть открытая позиция — закрываем по последней цене
        if позиция != 0 and len(данные) > 0:
            последняя_цена = float(данные.iloc[-1]["close"])
            капитал += позиция * (
                последняя_цена - цена_входа
                if позиция > 0
                else цена_входа - последняя_цена
            )

        # Рассчитываем метрики
        метрики = self._рассчитать_метрики(эквити_серия, сделки)

        return РезультатБэктеста(
            сделки=сделки,
            эквити=эквити_серия,
            история_позиций=pd.Series(история_позиций),
            метрики=метрики,
        )

    def _рассчитать_метрики(
        self,
        эквити: pd.Series,
        сделки: list[Сделка],
    ) -> dict:
        """
        Рассчитывает метрики производительности бэктеста.

        Параметры
        ----------
        эквити : pd.Series
            Кривая капитала.
        сделки : list[Сделка]
            Список совершённых сделок.

        Возвращает
        -------
        dict
            Словарь с метриками:
            - total_return — общая доходность в %
            - total_pnl — абсолютная прибыль
            - sharpe_ratio — коэффициент Шарпа
            - max_drawdown — максимальная просадка в %
            - win_rate — доля прибыльных сделок в %
            - num_trades — количество сделок
            - avg_win — средняя прибыль по прибыльным сделкам
            - avg_loss — средний убыток по убыточным сделкам
        """
        метрики: dict = {}

        # Общая доходность
        итоговый_капитал = float(эквити.iloc[-1])
        метрики["total_return"] = (
            (итоговый_капитал - self.начальный_капитал)
            / self.начальный_капитал
            * 100
        )
        метрики["total_pnl"] = итоговый_капитал - self.начальный_капитал

        # Коэффициент Шарпа (годовой)
        доходности = эквити.pct_change().dropna()
        if len(доходности) > 0 and доходности.std() > 0:
            метрики["sharpe_ratio"] = float(
                доходности.mean() / доходности.std() * np.sqrt(252 * 60)
                if len(доходности) > 1
                else 0.0
            )
        else:
            метрики["sharpe_ratio"] = 0.0

        # Максимальная просадка
        пик = эквити.cummax()
        просадка = (эквити - пик) / пик * 100
        метрики["max_drawdown"] = float(просадка.min())

        # Статистика по сделкам
        метрики["num_trades"] = len(сделки)
        if сделки:
            прибыльные = [с.pnl for с in сделки if с.pnl > 0]
            убыточные = [с.pnl for с in сделки if с.pnl <= 0]
            метрики["win_rate"] = (
                len(прибыльные) / len(сделки) * 100 if сделки else 0.0
            )
            метрики["avg_win"] = (
                np.mean(прибыльные) if прибыльные else 0.0
            )
            метрики["avg_loss"] = (
                np.mean(убыточные) if убыточные else 0.0
            )
            метрики["best_trade"] = max(
                сделки, key=lambda x: x.pnl_процент
            ).pnl_процент
            метрики["worst_trade"] = min(
                сделки, key=lambda x: x.pnl_процент
            ).pnl_процент
        else:
            метрики["win_rate"] = 0.0
            метрики["avg_win"] = 0.0
            метрики["avg_loss"] = 0.0
            метрики["best_trade"] = 0.0
            метрики["worst_trade"] = 0.0

        return метрики
