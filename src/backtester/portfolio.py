"""
Модуль тестирования портфелей инструментов.

Позволяет:
- Комбинировать несколько стратегий/инструментов в одном портфеле
- Задавать веса распределения капитала
- Выполнять ребалансировку
- Рассчитывать метрики портфеля в целом
"""

from dataclasses import dataclass, field
from typing import Optional

import numpy as np
import pandas as pd

from src.backtester.engine import Бэктестер, РезультатБэктеста, Сделка
from src.backtester.strategy import Стратегия


@dataclass
class ПозицияПортфеля:
    """
    Позиция одного инструмента в портфеле.

    Атрибуты
    ---------
    код : str
        Код инструмента.
    вес : float
        Доля капитала, распределённая на этот инструмент (0.0 - 1.0).
    стратегия : Стратегия
        Стратегия для этого инструмента.
    данные : pd.DataFrame
        Данные для тестирования.
    """
    код: str
    вес: float
    стратегия: Стратегия
    данные: pd.DataFrame


@dataclass
class РезультатПортфеля:
    """
    Результаты тестирования портфеля.

    Атрибуты
    ---------
    эквити : pd.Series
        Кривая капитала портфеля.
    результаты_инструментов : dict[str, РезультатБэктеста]
        Результаты по каждому инструменту.
    метрики : dict
        Метрики портфеля в целом.
    """
    эквити: pd.Series = field(default_factory=pd.Series)
    результаты_инструментов: dict[str, РезультатБэктеста] = field(
        default_factory=dict
    )
    метрики: dict = field(default_factory=dict)


class Портфель:
    """
    Управление и тестирование портфеля инструментов.

    Позволяет распределять капитал между несколькими инструментами
    с заданными весами и стратегиями.

    Параметры
    ----------
    начальный_капитал : float
        Начальный капитал портфеля (по умолчанию 100000).
    комиссия : float
        Комиссия на сделку в процентах (по умолчанию 0.01%).
    проскальзывание : float
        Проскальзывание в процентах (по умолчанию 0.01%).
    """

    def __init__(
        self,
        начальный_капитал: float = 100_000.0,
        комиссия: float = 0.0001,
        проскальзывание: float = 0.0001,
    ) -> None:
        self.начальный_капитал = начальный_капитал
        self.комиссия = комиссия
        self.проскальзывание = проскальзывание
        self.позиции: list[ПозицияПортфеля] = []

    def добавить(
        self,
        код: str,
        стратегия: Стратегия,
        данные: pd.DataFrame,
        вес: float = 1.0,
    ) -> None:
        """
        Добавляет инструмент в портфель.

        Параметры
        ----------
        код : str
            Код инструмента.
        стратегия : Стратегия
            Стратегия для этого инструмента.
        данные : pd.DataFrame
            Данные для тестирования.
        вес : float
            Вес инструмента в портфеле (доля капитала).
            По умолчанию 1.0 (равномерное распределение).
        """
        self.позиции.append(ПозицияПортфеля(
            код=код,
            вес=вес,
            стратегия=стратегия,
            данные=данные,
        ))

    def запустить(self) -> РезультатПортфеля:
        """
        Запускает тестирование портфеля.

        Для каждого инструмента запускается отдельный бэктест
        с долей капитала, пропорциональной весу инструмента.

        Возвращает
        -------
        РезультатПортфеля
            Результаты тестирования портфеля (кривая капитала, метрики).
        """
        if not self.позиции:
            raise ValueError("Портфель пуст. Добавьте инструменты через добавить().")

        # Нормализуем веса
        сумма_весов = sum(п.вес for п in self.позиции)
        if сумма_весов <= 0:
            raise ValueError("Сумма весов должна быть больше 0.")

        # Запускаем бэктест для каждого инструмента
        бэктестер = Бэктестер(
            начальный_капитал=self.начальный_капитал,
            комиссия=self.комиссия,
            проскальзывание=self.проскальзывание,
        )

        результаты_инструментов: dict[str, РезультатБэктеста] = {}

        for позиция in self.позиции:
            # Выделяем капитал на инструмент пропорционально весу
            капитал_инструмента = (
                self.начальный_капитал * позиция.вес / сумма_весов
            )
            бэктестер.начальный_капитал = капитал_инструмента
            результат = бэктестер.прогнать(
                позиция.стратегия,
                позиция.данные,
            )
            результаты_инструментов[позиция.код] = результат

        # Строим общую кривую капитала портфеля
        эквити_портфеля = self._построить_эквити_портфеля(результаты_инструментов)

        # Рассчитываем метрики портфеля
        метрики = self._рассчитать_метрики_портфеля(
            эквити_портфеля, результаты_инструментов
        )

        return РезультатПортфеля(
            эквити=эквити_портфеля,
            результаты_инструментов=результаты_инструментов,
            метрики=метрики,
        )

    def _построить_эквити_портфеля(
        self,
        результаты: dict[str, РезультатБэктеста],
    ) -> pd.Series:
        """
        Строит общую кривую капитала портфеля как сумму
        кривых капитала всех инструментов.

        Параметры
        ----------
        результаты : dict[str, РезультатБэктеста]
            Результаты по каждому инструменту.

        Возвращает
        -------
        pd.Series
            Кривая капитала портфеля.
        """
        if not результаты:
            return pd.Series(dtype=float)

        # Выравниваем все кривые капитала по общему индексу
        все_даты = pd.DatetimeIndex([])
        for результат in результаты.values():
            все_даты = все_даты.union(результат.эквити.index)
        все_даты = все_даты.sort_values()

        эквити = pd.Series(0.0, index=все_даты)
        for результат in результаты.values():
            # Заполняем пропуски последним известным значением
            выровненное = результат.эквити.reindex(все_даты, method="ffill")
            эквити = эквити.add(выровненное, fill_value=0)

        return эквити

    def _рассчитать_метрики_портфеля(
        self,
        эквити: pd.Series,
        результаты: dict[str, РезультатБэктеста],
    ) -> dict:
        """
        Рассчитывает метрики портфеля в целом.

        Параметры
        ----------
        эквити : pd.Series
            Кривая капитала портфеля.
        результаты : dict[str, РезультатБэктеста]
            Результаты по каждому инструменту.

        Возвращает
        -------
        dict
            Словарь с метриками портфеля.
        """
        метрики: dict = {}

        # Общая доходность портфеля
        итоговый_капитал = float(эквити.iloc[-1]) if len(эквити) > 0 else 0
        метрики["total_return"] = (
            (итоговый_капитал - self.начальный_капитал)
            / self.начальный_капитал
            * 100
        )
        метрики["total_pnl"] = итоговый_капитал - self.начальный_капитал

        # Коэффициент Шарпа портфеля
        доходности = эквити.pct_change().dropna()
        if len(доходности) > 0 and доходности.std() > 0:
            метрики["sharpe_ratio"] = float(
                доходности.mean() / доходности.std() * np.sqrt(252 * 60)
            )
        else:
            метрики["sharpe_ratio"] = 0.0

        # Максимальная просадка
        пик = эквити.cummax()
        просадка = (эквити - пик) / пик * 100
        метрики["max_drawdown"] = float(просадка.min())

        # Количество сделок и win rate по всем инструментам
        все_сделки = []
        for код, результат in результаты.items():
            for сделка in результат.сделки:
                все_сделки.append(сделка)

        метрики["num_trades"] = len(все_сделки)
        if все_сделки:
            прибыльные = [
                с.pnl for с in все_сделки if с.pnl > 0
            ]
            метрики["win_rate"] = (
                len(прибыльные) / len(все_сделки) * 100
            )
        else:
            метрики["win_rate"] = 0.0

        return метрики

    def корреляция_инструментов(
        self,
        результаты: dict[str, РезультатБэктеста],
    ) -> pd.DataFrame:
        """
        Рассчитывает корреляцию доходностей между инструментами портфеля.

        Параметры
        ----------
        результаты : dict[str, РезультатБэктеста]
            Результаты по каждому инструменту.

        Возвращает
        -------
        pd.DataFrame
            Матрица корреляции доходностей.
        """
        доходности: dict[str, pd.Series] = {}
        for код, результат in результаты.items():
            доходности[код] = результат.эквити.pct_change().dropna()

        df_доходности = pd.DataFrame(доходности)
        return df_доходности.corr()
