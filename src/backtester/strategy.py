"""
Базовый класс стратегии для бэктестера.

Предоставляет абстрактный интерфейс для создания торговых стратегий.
Пользовательские стратегии должны наследоваться от этого класса
и реализовывать методы init() и next().
"""

from abc import ABC, abstractmethod
from typing import Optional

import pandas as pd


class Стратегия(ABC):
    """
    Абстрактный базовый класс для всех торговых стратегий.

    Атрибуты
    ---------
    данные : pd.DataFrame
        DataFrame с колонками open, high, low, close, volume, open_interest.
    позиция : float
        Текущая позиция в единицах инструмента (положительная — long,
        отрицательная — short, 0 — нет позиции).
    """

    def __init__(self) -> None:
        self.данные: Optional[pd.DataFrame] = None
        self.позиция: float = 0.0
        self._индекс: int = 0
        self._сигналы: list[dict] = []
        self._название: str = self.__class__.__name__

    @property
    def название(self) -> str:
        """
        Возвращает название стратегии.
        """
        return self._название

    @название.setter
    def название(self, значение: str) -> None:
        """
        Устанавливает название стратегии.
        """
        self._название = значение

    @property
    def текущая_свеча(self) -> Optional[pd.Series]:
        """
        Возвращает текущую свечу (строку DataFrame) или None,
        если данные не загружены или индекс вне диапазона.
        """
        if self.данные is None or self._индекс >= len(self.данные):
            return None
        return self.данные.iloc[self._индекс]

    @property
    def сигналы(self) -> list[dict]:
        """
        Возвращает список всех сгенерированных сигналов.
        """
        return self._сигналы

    def установить_данные(self, данные: pd.DataFrame) -> None:
        """
        Устанавливает данные для стратегии.

        Параметры
        ----------
        данные : pd.DataFrame
            DataFrame с колонками open, high, low, close, volume.
        """
        self.данные = данные.copy()
        self._индекс = 0
        self.позиция = 0.0
        self._сигналы = []

    def купить(
        self,
        размер: float = 1.0,
        комментарий: Optional[str] = None,
    ) -> None:
        """
        Генерирует сигнал на покупку (открытие/увеличение long-позиции).

        Параметры
        ----------
        размер : float
            Размер позиции в единицах инструмента.
        комментарий : Optional[str]
            Комментарий к сигналу.
        """
        свеча = self.текущая_свеча
        if свеча is None:
            return
        self.позиция += размер
        self._сигналы.append({
            "datetime": свеча.name,
            "тип": "buy",
            "цена": float(свеча["close"]),
            "размер": размер,
            "комментарий": комментарий or "",
        })

    def продать(
        self,
        размер: float = 1.0,
        комментарий: Optional[str] = None,
    ) -> None:
        """
        Генерирует сигнал на продажу (открытие/увеличение short-позиции).

        Параметры
        ----------
        размер : float
            Размер позиции в единицах инструмента.
        комментарий : Optional[str]
            Комментарий к сигналу.
        """
        свеча = self.текущая_свеча
        if свеча is None:
            return
        self.позиция -= размер
        self._сигналы.append({
            "datetime": свеча.name,
            "тип": "sell",
            "цена": float(свеча["close"]),
            "размер": размер,
            "комментарий": комментарий or "",
        })

    def закрыть(
        self,
        комментарий: Optional[str] = None,
    ) -> None:
        """
        Генерирует сигнал на закрытие текущей позиции.

        Параметры
        ----------
        комментарий : Optional[str]
            Комментарий к сигналу.
        """
        свеча = self.текущая_свеча
        if свеча is None or self.позиция == 0:
            return
        self._сигналы.append({
            "datetime": свеча.name,
            "тип": "close",
            "цена": float(свеча["close"]),
            "размер": abs(self.позиция),
            "комментарий": комментарий or "",
        })
        self.позиция = 0.0

    @abstractmethod
    def init(self) -> None:
        """
        Инициализация стратегии (создание индикаторов, расчёт параметров).

        Вызывается один раз перед началом прогона по данным.
        """
        ...

    @abstractmethod
    def next(self) -> None:
        """
        Обработка очередной свечи.

        Вызывается для каждой свечи (строки данных).
        Здесь принимаются торговые решения.
        """
        ...

    def запустить(self) -> None:
        """
        Запускает стратегию на всех установленных данных.
        Последовательно вызывает next() для каждой свечи.
        """
        if self.данные is None:
            raise RuntimeError(
                "Данные не установлены. Вызовите установить_данные() перед запуском."
            )
        self.init()
        for i in range(len(self.данные)):
            self._индекс = i
            self.next()
