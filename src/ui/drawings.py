"""
Модуль инструментов рисования на свечном графике.

Поддерживает:
- Горизонтальные линии
- Вертикальные линии
- Трендовые линии (произвольный наклон)
- Текстовые метки
- Прямоугольники
- Фибоначчи-уровни
"""

from typing import Optional

import pyqtgraph as pg
from pyqtgraph.Qt import QtCore, QtGui, QtWidgets


class ГоризонтальнаяЛиния(pg.InfiniteLine):
    """
    Горизонтальная линия на графике.

    Параметры
    ----------
    цена : float
        Уровень цены, на котором разместить линию.
    цвет : tuple
        RGB-цвет линии (по умолчанию жёлтый).
    имя : str
        Название линии (отображается рядом).
    """

    def __init__(
        self,
        цена: float,
        цвет: tuple = (255, 200, 0),
        имя: str = "",
    ) -> None:
        super().__init__(
            pos=цена,
            angle=0,
            pen=pg.mkPen(цвет, width=1.5, style=QtCore.Qt.PenStyle.DashLine),
            movable=True,
            label=имя,
        )
        self.цена = цена


class ВертикальнаяЛиния(pg.InfiniteLine):
    """
    Вертикальная линия на графике (для отметки времени).

    Параметры
    ----------
    время : float
        Время в секундах (timestamp).
    цвет : tuple
        RGB-цвет линии (по умолчанию голубой).
    имя : str
        Название линии.
    """

    def __init__(
        self,
        время: float,
        цвет: tuple = (0, 200, 255),
        имя: str = "",
    ) -> None:
        super().__init__(
            pos=время,
            angle=90,
            pen=pg.mkPen(цвет, width=1.0, style=QtCore.Qt.PenStyle.DashLine),
            movable=True,
            label=имя,
        )


class ТекстоваяМетка(pg.TextItem):
    """
    Текстовая метка на графике.

    Параметры
    ----------
    текст : str
        Отображаемый текст.
    x : float
        Координата X (время в секундах).
    y : float
        Координата Y (цена).
    цвет : tuple
        RGB-цвет текста (по умолчанию белый).
    размер : int
        Размер шрифта (по умолчанию 10).
    """

    def __init__(
        self,
        текст: str,
        x: float,
        y: float,
        цвет: tuple = (255, 255, 255),
        размер: int = 10,
    ) -> None:
        super().__init__(text=текст, color=pg.mkColor(*цвет))
        self.setPos(x, y)
        шрифт = QtGui.QFont("Arial", размер)
        self.setFont(шрифт)


class Прямоугольник(pg.RectROI):
    """
    Прямоугольная область на графике.

    Параметры
    ----------
    x1 : float
        Левая граница (время).
    y1 : float
        Верхняя граница (цена).
    x2 : float
        Правая граница.
    y2 : float
        Нижняя граница.
    цвет : tuple
        RGB-цвет границы (по умолчанию синий).
    """

    def __init__(
        self,
        x1: float,
        y1: float,
        x2: float,
        y2: float,
        цвет: tuple = (80, 150, 255),
    ) -> None:
        ширина = abs(x2 - x1)
        высота = abs(y2 - y1)
        x = min(x1, x2)
        y = min(y1, y2)
        super().__init__(
            pos=(x, y),
            size=(ширина, высота),
            pen=pg.mkPen(цвет, width=1.5),
            removable=True,
        )


class ТрендоваяЛиния(pg.PolyLineROI):
    """
    Трендовая линия (произвольный наклон).

    Создаётся по двум точкам, можно перемещать и изменять.

    Параметры
    ----------
    x1 : float
        X первой точки (время).
    y1 : float
        Y первой точки (цена).
    x2 : float
        X второй точки.
    y2 : float
        Y второй точки.
    цвет : tuple
        RGB-цвет линии (по умолчанию оранжевый).
    """

    def __init__(
        self,
        x1: float,
        y1: float,
        x2: float,
        y2: float,
        цвет: tuple = (255, 150, 50),
    ) -> None:
        точки = [
            (x1, y1),
            (x2, y2),
        ]
        super().__init__(
            positions=точки,
            pen=pg.mkPen(цвет, width=2.0),
            movable=True,
            removable=True,
        )


class ИнструментыРисования:
    """
    Менеджер инструментов рисования для графика pyqtgraph.

    Позволяет добавлять, удалять и управлять
    графическими объектами на графике.

    Параметры
    ----------
    график : pg.PlotWidget
        Виджет графика, на котором будут отображаться рисунки.
    """

    def __init__(self, график: pg.PlotWidget) -> None:
        self.график = график
        self._рисунки: dict[str, list] = {
            "линии": [],
            "метки": [],
            "фигуры": [],
        }

    def добавить_горизонтальную_линию(
        self,
        цена: float,
        цвет: tuple = (255, 200, 0),
        имя: str = "",
    ) -> ГоризонтальнаяЛиния:
        """
        Добавляет горизонтальную линию на график.

        Параметры
        ----------
        цена : float
            Уровень цены.
        цвет : tuple
            RGB-цвет.
        имя : str
            Название линии.

        Возвращает
        -------
        ГоризонтальнаяЛиния
        """
        линия = ГоризонтальнаяЛиния(цена, цвет, имя)
        self.график.addItem(линия)
        self._рисунки["линии"].append(линия)
        return линия

    def добавить_вертикальную_линию(
        self,
        время: float,
        цвет: tuple = (0, 200, 255),
        имя: str = "",
    ) -> ВертикальнаяЛиния:
        """
        Добавляет вертикальную линию на график.

        Параметры
        ----------
        время : float
            Время в секундах (timestamp).
        цвет : tuple
            RGB-цвет.
        имя : str
            Название линии.

        Возвращает
        -------
        ВертикальнаяЛиния
        """
        линия = ВертикальнаяЛиния(время, цвет, имя)
        self.график.addItem(линия)
        self._рисунки["линии"].append(линия)
        return линия

    def добавить_текстовую_метку(
        self,
        текст: str,
        x: float,
        y: float,
        цвет: tuple = (255, 255, 255),
        размер: int = 10,
    ) -> ТекстоваяМетка:
        """
        Добавляет текстовую метку на график.

        Параметры
        ----------
        текст : str
            Текст метки.
        x : float
            Координата X (timestamp).
        y : float
            Координата Y (цена).
        цвет : tuple
            RGB-цвет.
        размер : int
            Размер шрифта.

        Возвращает
        -------
        ТекстоваяМетка
        """
        метка = ТекстоваяМетка(текст, x, y, цвет, размер)
        self.график.addItem(метка)
        self._рисунки["метки"].append(метка)
        return метка

    def добавить_прямоугольник(
        self,
        x1: float,
        y1: float,
        x2: float,
        y2: float,
        цвет: tuple = (80, 150, 255),
    ) -> Прямоугольник:
        """
        Добавляет прямоугольник на график.

        Параметры
        ----------
        x1 : float
            Левая граница (timestamp).
        y1 : float
            Верхняя граница (цена).
        x2 : float
            Правая граница.
        y2 : float
            Нижняя граница.
        цвет : tuple
            RGB-цвет.

        Возвращает
        -------
        Прямоугольник
        """
        прямоугольник = Прямоугольник(x1, y1, x2, y2, цвет)
        self.график.addItem(прямоугольник)
        self._рисунки["фигуры"].append(прямоугольник)
        return прямоугольник

    def добавить_трендовую_линию(
        self,
        x1: float,
        y1: float,
        x2: float,
        y2: float,
        цвет: tuple = (255, 150, 50),
    ) -> ТрендоваяЛиния:
        """
        Добавляет трендовую линию на график.

        Параметры
        ----------
        x1 : float
            X первой точки.
        y1 : float
            Y первой точки.
        x2 : float
            X второй точки.
        y2 : float
            Y второй точки.
        цвет : tuple
            RGB-цвет.

        Возвращает
        -------
        ТрендоваяЛиния
        """
        линия = ТрендоваяЛиния(x1, y1, x2, y2, цвет)
        self.график.addItem(линия)
        self._рисунки["фигуры"].append(линия)
        return линия

    def удалить_все(self) -> None:
        """Удаляет все рисунки с графика."""
        for категория in self._рисунки.values():
            for объект in категория:
                self.график.removeItem(объект)
            категория.clear()

    def получить_все(self) -> list:
        """
        Возвращает список всех рисунков.

        Возвращает
        -------
        list
            Список всех графических объектов.
        """
        все = []
        for категория in self._рисунки.values():
            все.extend(категория)
        return все
